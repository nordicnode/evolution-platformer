//! **The Phase 0 practice suite: generated, certified, reproducible.**
//!
//! The plan's later phases need a fixed set of problems whose answer is not in doubt. The
//! hand-drawn pack is a good difficulty ladder, but it is *authored*: a level that turns out to
//! be unbeatable, or one whose route the planner cannot compile, is a week of level design away
//! from being fixed. This module generates a small suite instead and certifies every level with
//! the two authorities the project already trusts:
//!
//! * the **reachability oracle** ([`crate::reach::report`]) says the flag can be reached in
//!   principle — the answer is a proof about the jump graph, not a lucky episode;
//! * the **timed planner** ([`crate::plan::verdict`]) says there is a line a policy can run, which
//!   is the stronger property Phase 1's route compiler needs.
//!
//! A level in this suite is only kept when **both** say yes. Generation is deterministic: level
//! `i` is a pure function of `i` and the two version constants below, so the committed files in
//! `levels/practice/` can be regenerated byte for byte and a change to the suite is a change to
//! this file rather than to twenty-four JSON files by hand.
//!
//! ## What the suite is, and what it is not
//!
//! Twenty-four levels: six archetypes at four tiers. Each is a left-to-right chain of ground
//! bands — the same shape as the pack's opening levels — built from a single mechanic family:
//!
//! | archetype | what it varies |
//! |---|---|
//! | `gap` | jumpable pits, 2-4 wide |
//! | `spike` | spike strips on the ground, 1-3 wide |
//! | `step` | one- and two-tile steps up and down |
//! | `crumble` | brittle bridges over a pit (walk across before the fuse burns) |
//! | `mover` | a sliding deck over a wide pit (get on, ride, get off) |
//! | `mixed` | every feature above in one chain |
//!
//! They are deliberately **deterministic**: no walkers, flyers or turrets. A patrol phase is drawn
//! from the episode seed, and a gate whose episodes re-roll the world measures the patrol as much
//! as the policy. The battery (`levels/bat-*.json`) already owns stochastic mechanics; this suite
//! owns *leg structure*, which is what the telemetry reads and what a route compiler compiles. A
//! later phase can add a stochastic tier without moving the ground under this one.
//!
//! The fallback is part of the generator, not a promise: if a seeded layout fails either
//! certification, the next attempt replaces the risky feature with a plain gap. The last attempt
//! for every level is a gap chain, which the pack has solved since its first level. So
//! [`generate`] tries hard never to return an uncertified level, and the suite's own test fails
//! loudly if one ever gets through — rather than a training run discovering it.
//!
//! ## Cost
//!
//! Generation is microseconds; certification is the cost, and it is why this is a command and a
//! test rather than something a trainer does before breakfast. A level costs one oracle sweep plus
//! one beam search (both bounded by the level's width). The `fuzz` command times a fresh parse and
//! certification of every file, so the suite's price is a reading rather than an estimate.

use crate::level::{Level, Tile};
use crate::plan::{self, PlanConfig, PlanVerdict};
use crate::reach;

/// Bumped when a change to the grammar would produce different levels. Committed suite files
/// carry this in their name's generation note rather than in the JSON format, which they do not
/// change: a suite file is an ordinary level file.
pub const SUITE_VERSION: u32 = 1;

/// Levels in the suite: six archetypes × four tiers.
pub const SUITE_LEN: usize = 24;

/// Ground row, and therefore the top of the walkable surface, for every generated level.
const GROUND: i32 = 13;
const HEIGHT: i32 = 15;

/// The archetypes, in the order the suite's indices cycle through them.
pub const ARCHETYPES: [&str; 6] = ["gap", "spike", "step", "crumble", "mover", "mixed"];

/// What one generated level's certification found.
#[derive(Clone, Debug)]
pub struct Certification {
    /// The reachability oracle says the flag is reachable.
    pub beatable: bool,
    /// The timed planner found a line that wins.
    pub planned: bool,
    /// Frames the planned line took, when there is one.
    pub frames: Option<u32>,
    /// Decision blocks in the planned line.
    pub blocks: Option<usize>,
    /// The verdict in its own words (the planner's, or the oracle's diagnosis).
    pub note: String,
}

impl Certification {
    /// Both authorities agree: this is a suite level.
    pub fn certified(&self) -> bool {
        self.beatable && self.planned
    }
}

/// The archetype of level `index`.
pub fn archetype(index: usize) -> &'static str {
    ARCHETYPES[index % ARCHETYPES.len()]
}

/// The tier of level `index`, `0..=3`.
pub fn tier(index: usize) -> usize {
    (index % SUITE_LEN) / ARCHETYPES.len()
}

/// The file stem a suite level is committed under: `p01-gap-t0`.
pub fn stem(index: usize) -> String {
    format!("p{:02}-{}-t{}", index + 1, archetype(index), tier(index))
}

/// The level's display name. It names the suite version, because a level's own name is what a
/// shelf card and a run's artifacts carry, and two grammars that generated the same stem are two
/// different problems.
pub fn name(index: usize) -> String {
    format!(
        "P{:02} {} tier {} (suite v{})",
        index + 1,
        archetype(index),
        tier(index),
        SUITE_VERSION
    )
}

/// Generate and certify one suite level.
///
/// Deterministic in `index`: the attempt loop, the per-attempt seed and the fallback are all
/// pure functions of the index and the constants above.
pub fn generate(index: usize) -> (Level, Certification) {
    let index = index % SUITE_LEN;
    let mut last = None;
    for attempt in 0..4 {
        // The first two attempts use the archetype's own features; the last two fall back to
        // gaps. A fallback still produces a valid, certified level of the right length — it just
        // stops asking the risky mechanic to be the thing that makes it interesting.
        let safe = attempt >= 2;
        let level = build(index, attempt, safe);
        let certification = certify(&level);
        if certification.certified() {
            return (level, certification);
        }
        last = Some((level, certification));
    }
    // The safe attempt is a gap chain with four gaps; the pack's own opening levels prove the
    // shape. Reaching this line means the generator or the planner changed underneath it, and a
    // silent uncertified suite is worse than a loud fixture failure.
    last.expect("four attempts is not zero")
}

/// Every suite level with its certification, in index order. This is what `fuzz` writes and what
/// the suite's test asserts.
pub fn suite() -> Vec<(Level, Certification)> {
    (0..SUITE_LEN).map(generate).collect()
}

/// Run both authorities on a level and report what each said.
///
/// **No wall clock here.** `sim`'s determinism promise is that the simulator never reads a clock,
/// and a tooling module in the same crate should not be the exception that makes a reader check.
/// The `fuzz` command times this function from outside, on a level parsed fresh from its JSON, so
/// the number it prints is "open this file and certify it" rather than a warm in-memory repeat.
pub fn certify(level: &Level) -> Certification {
    let report = reach::report(level);
    if !report.goal_reached {
        return Certification {
            beatable: false,
            planned: false,
            frames: None,
            blocks: None,
            note: report
                .diagnosis
                .unwrap_or_else(|| "the flag cannot be reached".into()),
        };
    }
    // Depth 48 is the planner's "one long crossing past the default" budget, the same shape
    // `plan --max-depth` exposes. These levels are short chains, so the search either finds the
    // line well inside it or the level is not the simple thing the grammar meant to build.
    let verdict = plan::verdict(
        level,
        0x5EED,
        PlanConfig {
            depth: 48,
            ..PlanConfig::default()
        },
    );
    match verdict {
        PlanVerdict::Planned {
            frames,
            blocks,
            hops: _,
        } => Certification {
            beatable: true,
            planned: true,
            frames: Some(frames),
            blocks: Some(blocks),
            note: format!("{blocks} blocks, {frames} frames"),
        },
        other => Certification {
            beatable: true,
            planned: false,
            frames: None,
            blocks: None,
            note: other.detail(),
        },
    }
}

/// A feature the grammar can place. Kept private: the suite's *shape* is the stable contract, not
/// the sequence of instructions that made it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Feature {
    Gap(i32),
    Spikes(i32),
    Step(i32),
    Crumble(i32),
    Mover(i32),
    Rest(i32),
}

/// Deterministic per-level randomness: splitmix64 over `(index, attempt, salt)`.
///
/// A hash rather than a stateful RNG on purpose: every feature's width is a pure function of its
/// position in the level, so inserting a feature in the grammar does not shift every later draw
/// (the failure mode of a stateful stream, and the reason a "reproducible" generator that streams
/// is only reproducible until somebody edits it).
fn pick(index: usize, attempt: usize, salt: u64, lo: i32, hi: i32) -> i32 {
    debug_assert!(lo <= hi);
    let mut x = 0x9E37_79B9_7F4A_7C15u64
        ^ (index as u64).wrapping_mul(0xD1B5_4A32_D192_ED03)
        ^ (attempt as u64).wrapping_mul(0x94D0_49BB_1331_11EB)
        ^ salt.wrapping_mul(0x2545_F491_4F6C_DD1D);
    x ^= x >> 30;
    x = x.wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x ^= x >> 27;
    x = x.wrapping_mul(0x94D0_49BB_1331_11EB);
    x ^= x >> 31;
    lo + (x % (hi - lo + 1) as u64) as i32
}

/// Build attempt `attempt` of level `index`.
fn build(index: usize, attempt: usize, safe: bool) -> Level {
    let width = 58 + tier(index) as i32 * 8 + pick(index, attempt, 1, 0, 6);
    let mut layout = Layout::new(name(index), width);
    layout.ground_run(6);
    let archetype = archetype(index);
    // A fixed number of feature slots rather than "until the width runs out": the number of
    // crossings is the level's *design* (and its leg count), so a wider tier has more room between
    // crossings, not a different route shape.
    let slots = 3 + tier(index) as i32;
    for slot in 0..slots {
        layout.ground_run(pick(index, attempt, 10 + slot as u64, 2, 4));
        let feature = pick_feature(archetype, index, attempt, slot as u64, safe);
        layout.place(feature);
    }
    layout.finish();
    layout.level
}

/// Which feature a slot gets. The archetype's own family dominates; the rest are connective tissue
/// (a rest stretch) or the fallback (a gap).
fn pick_feature(archetype: &str, index: usize, attempt: usize, slot: u64, safe: bool) -> Feature {
    let t = tier(index) as i32;
    let roll = pick(index, attempt, 100 + slot, 0, 99);
    let gap = Feature::Gap(pick(index, attempt, 200 + slot, 2, 3 + t.min(1)));
    if safe {
        return match archetype {
            // A safe fallback still varies its *own* safe feature: spikes and steps are certified
            // by the pack's own levels, and a tier that flattened to identical gap chains would
            // make the last two tiers redundant.
            "spike" if roll < 50 => Feature::Spikes(pick(index, attempt, 300 + slot, 1, 2)),
            "step" if roll < 50 => Feature::Step(pick(index, attempt, 400 + slot, -1, 1)),
            _ => gap,
        };
    }
    match archetype {
        "gap" => {
            if roll < 70 {
                gap
            } else {
                Feature::Rest(pick(index, attempt, 500 + slot, 2, 4))
            }
        }
        "spike" => {
            if roll < 65 {
                Feature::Spikes(pick(index, attempt, 600 + slot, 1, 2 + t.min(1)))
            } else {
                Feature::Rest(pick(index, attempt, 700 + slot, 2, 3))
            }
        }
        "step" => {
            if roll < 70 {
                let delta = pick(index, attempt, 800 + slot, 0, 1);
                Feature::Step(if delta == 0 { -1 } else { 1 })
            } else {
                Feature::Rest(2)
            }
        }
        "crumble" => {
            if roll < 60 {
                Feature::Crumble(pick(index, attempt, 900 + slot, 3, 4 + t.min(1)))
            } else {
                gap
            }
        }
        "mover" => {
            if roll < 55 {
                Feature::Mover(pick(index, attempt, 1000 + slot, 7, 8 + t * 2))
            } else {
                gap
            }
        }
        // Every family in one chain, with the tier choosing how often the hard ones come up.
        _ => match roll {
            0..=24 => gap,
            25..=44 => Feature::Spikes(pick(index, attempt, 1100 + slot, 1, 2 + t.min(1))),
            45..=64 => Feature::Crumble(pick(index, attempt, 1200 + slot, 3, 4 + t.min(1))),
            65..=84 => Feature::Step(pick(index, attempt, 1300 + slot, -1, 1)),
            _ => Feature::Mover(pick(index, attempt, 1400 + slot, 6, 7 + t)),
        },
    }
}

/// The cursor and the current ground height while a level is painted.
struct Layout {
    level: Level,
    x: i32,
    ground: i32,
}

impl Layout {
    fn new(name: String, width: i32) -> Layout {
        let mut level = Level::starter(name, width, HEIGHT);
        // The starter's floor is one row; this suite's levels are two rows thick so a pit reads
        // as a pit rather than as a thin line, and so a body that falls in is visibly gone.
        for x in 0..width {
            for y in 0..HEIGHT {
                level.set_tile(x, y, Tile::Empty);
            }
        }
        // The starter's own goal comes off; `finish` places the real one. The old one is an
        // entity, not a tile, so clearing the grid did not remove it and leaving it would give
        // the level two flags and `validate` would refuse it.
        for (gx, gy) in level.goal_tiles() {
            level.remove_goal_at(gx, gy);
        }
        level.set_spawn_tile(2, GROUND - 1);
        Layout {
            level,
            x: 0,
            ground: GROUND,
        }
    }

    fn ground_run(&mut self, n: i32) {
        for _ in 0..n {
            self.ground_column();
        }
    }

    fn ground_column(&mut self) {
        let x = self.x;
        if x < 0 || x >= self.level.width {
            return;
        }
        for y in self.ground..HEIGHT {
            self.level.set_tile(x, y, Tile::Solid);
        }
        self.x += 1;
    }

    fn place(&mut self, feature: Feature) {
        match feature {
            Feature::Rest(n) => self.ground_run(n),
            Feature::Gap(n) => {
                for _ in 0..n {
                    self.empty_column();
                }
            }
            Feature::Spikes(n) => {
                for _ in 0..n {
                    let x = self.x;
                    self.ground_column();
                    if x < self.level.width {
                        self.level.set_tile(x, self.ground - 1, Tile::Spike);
                    }
                }
            }
            Feature::Step(delta) => {
                self.ground = (self.ground + delta).clamp(8, GROUND);
                self.ground_run(2);
            }
            Feature::Crumble(n) => {
                // A bridge, not a floor: one brittle row over empty space. The body has to commit
                // to it, which is what makes it a *leg* rather than a spike with a fuse.
                for _ in 0..n {
                    let x = self.x;
                    if x >= self.level.width {
                        break;
                    }
                    self.level.set_tile(x, self.ground, Tile::Cracked);
                    self.x += 1;
                }
            }
            Feature::Mover(span) => {
                // The pit, then the deck that crosses it. The deck is authored at `ground - 1`,
                // which puts its top exactly at the ground's surface, so boarding it is a step
                // rather than a jump — the interesting part is the wait and the ride, not a
                // precision landing.
                let start = self.x;
                for _ in 0..span {
                    self.empty_column();
                }
                let tiles = 3;
                let travel = (span - tiles).max(2);
                // Anchored at the pit's own first column, so the deck's near end is the ledge
                // the body steps off from and its far end is the far ledge: the ride is the
                // crossing rather than an extra gap at either end of it.
                let _ =
                    self.level
                        .add_platform_tile(start, self.ground - 1, tiles, travel, false, 1);
            }
        }
    }

    fn empty_column(&mut self) {
        let x = self.x;
        if x < 0 || x >= self.level.width {
            return;
        }
        for y in 0..HEIGHT {
            self.level.set_tile(x, y, Tile::Empty);
        }
        self.x += 1;
    }

    /// Fill the rest of the width with ground and put the flag on the last safe tile.
    fn finish(&mut self) {
        while self.x < self.level.width {
            self.ground_column();
        }
        let goal_x = self.level.width - 3;
        let placed = self.level.set_goal_tile(goal_x, self.ground - 1);
        // `set_goal_tile` refuses a cell without ground under it or with the flag's two-cell
        // marker blocked. The fill above guarantees the first; a level whose final feature is a
        // pit is filled by the same loop, so the second holds too. If a future grammar breaks
        // that, walk back to the last place it does hold rather than writing a level with no flag.
        if !placed {
            for x in (2..goal_x).rev() {
                if self.level.set_goal_tile(x, self.ground - 1) {
                    break;
                }
            }
        }
    }
}

impl Layout {
    /// Test-only view of where the paint cursor ended, for the generator's own shape assertions.
    #[cfg(test)]
    fn painted_width(&self) -> i32 {
        self.x
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_suite_is_twenty_four_levels_of_six_archetypes() {
        assert_eq!(SUITE_LEN, 24);
        for index in 0..SUITE_LEN {
            assert_eq!(archetype(index), ARCHETYPES[index % ARCHETYPES.len()]);
            assert_eq!(tier(index), index / ARCHETYPES.len());
            assert!(stem(index).starts_with(&format!("p{:02}-", index + 1)));
        }
    }

    #[test]
    fn generation_is_deterministic() {
        // The committed files are generated from this function, so two calls have to be the same
        // bytes. Comparing JSON rather than the struct also catches a field the writer drops.
        for index in [0usize, 5, 11, 23] {
            let (a, _) = generate(index);
            let (b, _) = generate(index);
            assert_eq!(a.to_json_pretty().unwrap(), b.to_json_pretty().unwrap());
        }
    }

    #[test]
    fn every_generated_level_is_beatable_plannable_and_committed() {
        // The Phase 0 gate, at suite scale: no level enters the committed pack unless the oracle
        // and the planner both agree, and the file on disk is the one this generator produces.
        // Slow by test standards (a beam search per level) and worth it — this is the fixture
        // later phases will trust. Byte equality is checked in the same pass rather than a second
        // one, because generation is the expensive half and a separate test would double it.
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../levels/practice");
        for index in 0..SUITE_LEN {
            let (level, cert) = generate(index);
            assert!(
                cert.beatable,
                "{} is not beatable: {}",
                stem(index),
                cert.note
            );
            assert!(
                cert.planned,
                "{} is beatable but the planner found no line: {}",
                stem(index),
                cert.note
            );
            assert!(cert.frames.is_some(), "{} has no timed route", stem(index));
            // The writer round-trips, which is what the committed file must do.
            let json = level.to_json_pretty().expect("a generated level writes");
            let back = Level::from_json_str(&json).expect("and reads back");
            assert_eq!(back.content_hash_string(), level.content_hash_string());
            // And the committed file *is* that JSON: `train-cli fuzz --out` is the writer, so a
            // suite file edited by hand is caught here rather than becoming a problem whose
            // certification was never re-run.
            let path = dir.join(format!("{}.json", stem(index)));
            let on_disk = std::fs::read_to_string(&path).unwrap_or_else(|e| {
                panic!(
                    "{}: {e} — run `train-cli fuzz --out levels/practice`",
                    path.display()
                )
            });
            assert_eq!(
                on_disk,
                json,
                "{} differs from the generator; regenerate the suite",
                path.display()
            );
        }
    }

    #[test]
    fn the_suite_exercises_more_than_one_mechanic() {
        // A generator whose fallback swallowed every archetype would still pass the certification
        // test above while producing twenty-four copies of the same gap chain. Count the tiles the
        // suite actually places, so a silent regression to "all gaps" is a failure.
        let mut spikes = 0;
        let mut cracked = 0;
        let mut platforms = 0;
        let mut steps = 0;
        for index in 0..SUITE_LEN {
            let (level, _) = generate(index);
            spikes += level
                .to_glyph_rows()
                .iter()
                .map(|row| row.chars().filter(|c| *c == '^').count())
                .sum::<usize>();
            cracked += level
                .to_glyph_rows()
                .iter()
                .map(|row| row.chars().filter(|c| *c == 'd').count())
                .sum::<usize>();
            platforms += level.platforms.len();
            // A step exists when some column's ground top differs from the base row.
            let tops: Vec<i32> = (0..level.width)
                .map(|x| {
                    (0..HEIGHT)
                        .find(|y| level.get(x, *y) == Tile::Solid)
                        .unwrap_or(HEIGHT)
                })
                .collect();
            if tops.iter().any(|top| *top != GROUND) {
                steps += 1;
            }
        }
        assert!(spikes > 0, "no spike strips in the suite");
        assert!(cracked > 0, "no brittle bridges in the suite");
        assert!(platforms > 0, "no moving decks in the suite");
        assert!(steps > 0, "no stepped ground in the suite");
    }

    #[test]
    fn the_layout_never_runs_past_its_width() {
        for index in 0..SUITE_LEN {
            let (level, _) = generate(index);
            assert_eq!(level.width, level.width.max(8));
            assert!(
                level.goal_tiles().len() == 1,
                "{} has {} flags",
                stem(index),
                level.goal_tiles().len()
            );
        }
        // And the paint cursor's invariant is the one the grammar depends on: a feature may not
        // move it backwards, and `finish` leaves it at the width.
        let mut layout = Layout::new("cursor".into(), 40);
        layout.ground_run(3);
        layout.place(Feature::Gap(2));
        layout.place(Feature::Step(1));
        let reached = layout.painted_width();
        assert!(reached >= 7, "the cursor advanced past the features");
        layout.finish();
        assert_eq!(layout.painted_width(), layout.level.width);
    }
}
